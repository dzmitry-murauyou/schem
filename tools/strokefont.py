# characters that only occupy half a cell
NARROW = set(".,:;'`!")


def text_polylines(s, x, y, size, rot=0, align="start", anchor="baseline"):
    """Turn a string into a list of polylines in board millimetres.

    size   - cap height in mm
    rot    - 0, 90, 180 or 270 degrees, counter-clockwise
    align  - 'start' | 'middle' | 'end'  (horizontal placement of the string)
    anchor - 'baseline' | 'middle'
    """
    k = size / 6.0                       # grid -> mm
    adv = 6.0                            # grid units per character
    # total advance
    total = 0.0
    widths = []
    for ch in s:
        w = 3.0 if ch in NARROW else adv
        widths.append(w)
        total += w
    total = max(total - (adv - 4.0), 0.0) if s else 0.0
    if align == "middle":
        px = -total * k / 2.0
    elif align == "end":
        px = -total * k
    else:
        px = 0.0
    py = 0.0 if anchor == "baseline" else -3.0 * k

    out = []
    for ch, w in zip(s, widths):
        g = GLYPHS.get(ch.upper() if ch != "µ" else ch)
        if g is None:
            g = GLYPHS.get("?") or []
        for line in g:
            out.append([(px + u * k, py + v * k) for u, v in line])
        px += w * k

    if rot == 0:
        return [[(x + a, y + b) for a, b in L] for L in out]
    if rot == 90:
        return [[(x - b, y + a) for a, b in L] for L in out]
    if rot == 180:
        return [[(x - a, y - b) for a, b in L] for L in out]
    if rot == 270:
        return [[(x + b, y - a) for a, b in L] for L in out]
    raise ValueError("rotation %s" % rot)


def text_width(s, size):
    adv = 6.0
    total = 0.0
    for ch in s:
        total += 3.0 if ch in NARROW else adv
    return max(total - (adv - 4.0), 0.0) * size / 6.0
